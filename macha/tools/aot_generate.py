#!/usr/bin/env python3
"""Generate graph-specific native Zig code from WireWarp v1 .wwir files.
No dependencies. Emits code only, never executes content from the input file.
"""
import argparse, hashlib, struct, json
from pathlib import Path
from dataclasses import dataclass

MAGIC = 0xBADBEEF
@dataclass(frozen=True)
class Node:
    kind: int
    id: int
    edges: tuple[int, ...]

def parse(data):
    if len(data) < 68 or struct.unpack_from('<II', data) != (MAGIC, 1):
        raise ValueError('Not a WireWarp v1 wiring file')
    count, *offs = struct.unpack_from('<i6I', data, 40)
    if count != 6 or offs[0] != 68 or offs[-1] != len(data) or any(b-a<4 for a,b in zip(offs,offs[1:])):
        raise ValueError('Invalid group boundaries')
    groups=[]; next_id=0
    for start,end in zip(offs,offs[1:]):
        n, = struct.unpack_from('<i',data,start); p=start+4; nodes=[]
        if not 0 <= n <= (end-p)//9: raise ValueError('Invalid record count')
        for _ in range(n):
            if p+9>end: raise ValueError('Truncated node')
            k,i,m=struct.unpack_from('<Bii',data,p); p+=9
            if i!=next_id or not 0<=m<=(end-p)//4: raise ValueError('Invalid ID or fanout count')
            e=struct.unpack_from(f'<{m}i',data,p);p+=4*m; next_id+=1
            nodes.append(Node(k,i,e))
        if p!=end: raise ValueError('Unexpected group bytes')
        groups.append(nodes)
    return groups

def topology(groups):
    inputs,outputs,lamps,gates,wires=groups
    I,O,L,G,W=map(len,groups); lb=I+O; gb=lb+L; wb=gb+G
    def in_range(edges,lo,hi): return all(lo<=x<hi for x in edges)
    if any(not in_range(n.edges,wb,wb+W) for n in inputs+gates): raise ValueError('Invalid source fanout')
    if any(n.kind not in range(1,5) or not in_range(n.edges,I,gb) for n in wires): raise ValueError('Invalid wire')
    if any(n.edges for n in outputs): raise ValueError('Unexpected output fanout')
    normal=[[] for _ in gates]; faulty=[0]*G; owners=[]
    for n in lamps:
        if n.kind not in (1,2,3) or len(n.edges)!=1 or not in_range(n.edges,gb,wb): raise ValueError('Invalid lamp')
        gi=n.edges[0]-gb; owners.append(gi)
        if n.kind==3: faulty[gi]+=1
        else: normal[gi].append(n.id-lb)
    for gi,n in enumerate(gates):
        if n.kind not in range(1,8) or not normal[gi] or faulty[gi]>1 or (n.kind==7 and not faulty[gi]): raise ValueError('Unsupported gate')
    targets=[]
    for n in wires:
        ts=[]
        for t in n.edges:
            if t<lb: ts.append((3,t-I))
            else:
                li=t-lb; gi=owners[li]
                ts.append((2,gi) if lamps[li].kind==3 else (1 if faulty[gi] else 0,li))
        targets.append(sorted(ts))
    return targets,owners,normal,faulty

def generate(data, max_wire=64, max_actions=100000, max_gates=10000):
    groups=parse(data); targets,owners,normal,faulty=topology(groups)
    gates=groups[3]
    h=hashlib.sha256(data).digest()
    lines=['// Generated by aot_generate.py. Do not edit.', 'const std = @import("std");', 'pub const enabled = true;', 'pub const fused = false;', 'pub const digest: [32]u8 = .{ '+', '.join(str(x) for x in h)+' };', 'pub fn trip(self: anytype, w: usize) std.mem.Allocator.Error!bool {', '    switch (w) {']
    count=actions=0
    for wi,ts in enumerate(targets):
        if not ts or len(ts)>max_wire or actions+len(ts)>max_actions: continue
        lines.append(f'        {wi} => {{')
        for kind,idx in ts:
            if kind in (0,1):
                lines.append(f'            self.g.lamps[{idx}].on = !self.g.lamps[{idx}].on;')
                if kind==0: lines.append(f'            self.dirty.push({owners[idx]});')
            elif kind==2:
                if len(normal[idx])>1: lines.append(f'            self.fault_hits[{idx}] += 1;')
                lines.append(f'            self.dirty.push({idx});')
            else: lines.append(f'            try self.out.append(self.alloc, {idx});')
        lines.extend(['            return true;', '        },']);count+=1;actions+=len(ts)
    # With no cases Zig would flag unused self. Use explicit discard only then.
    if not count: lines.insert(next(i for i,l in enumerate(lines) if l.startswith('    switch (w)')), '    _ = self;')
    lines.extend(['        else => return false,','    }','}', 'pub fn evaluate(self: anytype, gi: usize) ?bool {','    switch (gi) {'])
    gc=0
    for gi,n in enumerate(gates):
        if gc>=max_gates: break
        ls=normal[gi]
        if faulty[gi]:
            if len(ls)!=1: continue # retain macha RNG exactly
            lines.append(f'        {gi} => return self.g.lamps[{ls[0]}].on,');gc+=1;continue
        if len(ls)>2: continue # generic evaluation for wide gates
        l=f'self.g.lamps[{ls[0]}].on'
        expr=l if len(ls)==1 else f'{l} '+('!=' if n.kind in (5,6) else 'and')+f' self.g.lamps[{ls[1]}].on'
        lines.append(f'        {gi} => {{ const cur = {expr}; const changed = cur != self.gate_state[{gi}]; self.gate_state[{gi}] = cur; return changed; }},');gc+=1
    if not gc: lines.insert(next(i for i,l in enumerate(lines) if l.startswith('    switch (gi)')), '    _ = self;')
    lines.extend(['        else => return null,','    }','}', NO_EVENT, ''])
    return '\n'.join(lines),dict(wires=count,total_wires=len(targets),actions=actions,gates=gc,total_gates=len(gates),sha256=h.hex())

NO_EVENT = "pub fn event(_: anytype, _: i32) std.mem.Allocator.Error!bool { return false; }"


def plan_event(groups, targets, owners, normal, faulty, port, max_cost=100000):
    """Prove a complete root transaction has a state-independent schedule.

    Each visited gate must be a non-fault single-input gate or two-input XOR/XNOR,
    with exactly one lamp hit in the entire transaction. Thus each gate changes
    once, from every consistent boundary state. Repeated visits, other gate
    classes, or fault effects reject the entire root (no partial execution).
    """
    inputs, outputs, lamps, gates, wires = groups
    wb=sum(map(len,groups[:4]))
    pending=sorted(w-wb for w in inputs[port].edges)
    seen=set(); lamp_ids=[]; gate_ids=[]; output_ids=[]; cost=0
    while pending:
        wave=[]
        for wi in pending:
            cost+=1
            if cost>max_cost: return None
            for kind,idx in targets[wi]:
                cost+=1
                if cost>max_cost: return None
                if kind==3:
                    output_ids.append(idx);continue
                if kind!=0: return None
                gi=owners[idx]
                if gi in seen or faulty[gi]: return None
                if not (len(normal[gi])==1 or (len(normal[gi])==2 and gates[gi].kind in (5,6))): return None
                seen.add(gi);lamp_ids.append(idx);gate_ids.append(gi);wave.append(gi)
        # The runtime sorts each gate's wires independently, preserving dirty order.
        pending=[]
        for gi in wave:
            edges=gates[gi].edges
            if cost+len(pending)+len(edges)>max_cost: return None
            pending.extend(sorted(w-wb for w in edges))
    return tuple(lamp_ids),tuple(gate_ids),tuple(output_ids)


def generate_fused(data, max_cost=100000, max_ports=1024):
    groups=parse(data);targets,owners,normal,faulty=topology(groups)
    digest=hashlib.sha256(data).digest()
    plans={}; used=0
    for port in range(len(groups[0])):
        if len(plans)>=max_ports or used>=max_cost: break
        plan=plan_event(groups,targets,owners,normal,faulty,port,max_cost-used)
        if plan is None: continue
        cost=max(1,sum(map(len,plan)))
        if used+cost>max_cost: continue
        plans[port]=plan;used+=cost
    lines=['// Generated event plans; no per-node specialization.', 'const std = @import("std");', 'pub const enabled = true;', 'pub const fused = true;', 'pub const digest: [32]u8 = .{ '+', '.join(map(str,digest))+' };',
        'pub fn trip(_: anytype, _: usize) std.mem.Allocator.Error!bool { return false; }', 'pub fn evaluate(_: anytype, _: usize) ?bool { return null; }',
        'fn apply(self: anytype, lamps: []const usize, gates: []const usize, outputs: []const i32) std.mem.Allocator.Error!bool {',
        '    try self.out.appendSlice(self.alloc, outputs);',
        '    for (lamps, gates) |li, gi| {',
        '        self.g.lamps[li].on = !self.g.lamps[li].on;',
        '        self.gate_state[gi] = !self.gate_state[gi];',
        '    }',
        '    self.checks += @as(u64, @intCast(gates.len));', '    return true;', '}',
        'pub fn event(self: anytype, port: i32) std.mem.Allocator.Error!bool {']
    if not plans: lines.append('    _ = self;')
    lines.append('    switch (port) {')
    def arr(xs):return '&.{'+', '.join(map(str,xs))+'}'
    for port,(ls,gs,os) in plans.items():
        lines.append(f'        {port} => return apply(self, {arr(ls)}, {arr(gs)}, {arr(os)}),')
    lines.extend(['        else => return false,','    }','}', ''])
    return '\n'.join(lines),dict(mode='fused',fused_ports=len(plans),total_ports=len(groups[0]),plan_entries=used,sha256=digest.hex())


STUB='''// Generic runtime only. Generated file replaces this on request.
const std = @import("std");
pub const enabled = false;
pub const fused = false;
pub const digest: [32]u8 = [_]u8{0} ** 32;
pub fn trip(self: anytype, w: usize) std.mem.Allocator.Error!bool { _ = self; _ = w; return false; }
pub fn evaluate(self: anytype, gi: usize) ?bool { _ = self; _ = gi; return null; }
pub fn event(_: anytype, _: i32) std.mem.Allocator.Error!bool { return false; }
'''

def load_mask_profile(path, data, digest):
    profile=json.loads(path.read_text(encoding='utf-8'))
    if not isinstance(profile,dict) or profile.get('sha256')!=digest:
        raise ValueError('Mask profile SHA-256 does not match graph')
    # The validated header contains the wire-group start at offset 60.
    wire_start=struct.unpack_from('<I',data,60)[0]
    wire_count=struct.unpack_from('<i',data,wire_start)[0]
    wires=profile.get('wires')
    if not isinstance(wires,list) or any(type(w) is not int or not 0<=w<wire_count for w in wires) or len(set(wires))!=len(wires):
        raise ValueError('Invalid or duplicate mask-profile wire index')
    return sorted(wires)

