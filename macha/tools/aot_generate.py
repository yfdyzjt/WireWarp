    p=argparse.ArgumentParser(description=__doc__);p.add_argument('wwir',nargs='?',type=Path);p.add_argument('--clear',action='store_true');p.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'src/core/AotGenerated.zig');p.add_argument('--max-wire',type=int,default=64);p.add_argument('--max-actions',type=int,default=100000);p.add_argument('--max-gates',type=int,default=10000);p.add_argument('--mode',choices=['node','fused','v3','v3.1','v3.2','v3.3','v3.4','v3.5','v4.0','v4.1'],default='node');p.add_argument('--max-fused-actions',type=int,default=100000);p.add_argument('--max-fused-ports',type=int,default=1024);p.add_argument('--mask-cap',type=int,default=2048);p.add_argument('--mask-profile',type=Path);a=p.parse_args()
